"""Apply the hand-written DDL the Alembic autogenerator cannot express.

Run once after `alembic revision --autogenerate` regenerates the initial
migration. Idempotent: re-running on an already-patched file is a no-op.

What it adds:
* ``import pgvector.sqlalchemy`` (autogenerate emits the type but not the import)
* ``CREATE EXTENSION vector / pg_trgm`` so migrations apply to a clean database
  with no ``infra/db/init.sql`` hook (this is what CI does)
* HNSW indexes on every vector column (ARCHITECTURE section 4 "Indexes:")
* the ``doc_chunks.tsv`` generated tsvector column + GIN index, i.e. the BM25
  half of the hybrid retrieval in ARCHITECTURE section 8
* trigram indexes used by pipeline 03's fuzzy name join and crosswalk lookup
"""

from __future__ import annotations

import pathlib
import sys

VERSIONS = pathlib.Path(__file__).resolve().parents[1] / "services/core/alembic/versions"

EXTENSIONS_BLOCK = '''def upgrade() -> None:
    # pgvector + pg_trgm must exist before any VECTOR column is created.
    # infra/db/init.sql does this on a fresh docker volume; CI has no such hook,
    # so the migration is self-sufficient (Gate 1: "migrations apply from a
    # clean database").
    op.execute("CREATE EXTENSION IF NOT EXISTS vector")
    op.execute("CREATE EXTENSION IF NOT EXISTS pg_trgm")

    # ### commands auto generated by Alembic - please adjust! ###'''

INDEX_BLOCK = '''    # ### end Alembic commands ###

    # ------------------------------------------------------------------
    # Hand-written objects the autogenerator cannot express.
    # ------------------------------------------------------------------

    # ARCHITECTURE section 4, "Indexes:" -> HNSW on BOTH vector columns.
    op.execute(
        "CREATE INDEX ix_qp_descriptions_embedding_hnsw ON qp_descriptions "
        "USING hnsw (embedding vector_cosine_ops)"
    )
    op.execute(
        "CREATE INDEX ix_doc_chunks_embedding_hnsw ON doc_chunks "
        "USING hnsw (embedding vector_cosine_ops)"
    )
    op.execute(
        "CREATE INDEX ix_crosswalk_embedding_hnsw ON crosswalk "
        "USING hnsw (embedding vector_cosine_ops)"
    )

    # ARCHITECTURE section 8: BM25 half of hybrid retrieval. Hindi/Marathi/
    # Telugu have no Postgres stemmer, so config 'simple' is the correct choice
    # (ARCHITECTURE section 8 names it explicitly). The section path is folded
    # into the indexed text because research.md section 9.2 shows multi-hop
    # questions cap Chain-MRR at 0.44 unless section paths ride along.
    op.execute(
        "ALTER TABLE doc_chunks ADD COLUMN tsv tsvector "
        "GENERATED ALWAYS AS (to_tsvector('simple', coalesce(section,'') || ' ' || chunk)) STORED"
    )
    op.execute("CREATE INDEX ix_doc_chunks_tsv ON doc_chunks USING gin (tsv)")

    # Fuzzy phrase lookup for the crosswalk and for pipeline 03's name join.
    op.execute("CREATE INDEX ix_crosswalk_phrase_trgm ON crosswalk USING gin (phrase gin_trgm_ops)")
    op.execute(
        "CREATE INDEX ix_courses_sub_course_trgm ON courses USING gin (sub_course gin_trgm_ops)"
    )
    op.execute(
        "CREATE INDEX ix_qualifications_name_trgm ON qualifications USING gin (name gin_trgm_ops)"
    )


def downgrade() -> None:'''

DOWNGRADE_BLOCK = '''def downgrade() -> None:
    for stmt in (
        "DROP INDEX IF EXISTS ix_qualifications_name_trgm",
        "DROP INDEX IF EXISTS ix_courses_sub_course_trgm",
        "DROP INDEX IF EXISTS ix_crosswalk_phrase_trgm",
        "DROP INDEX IF EXISTS ix_doc_chunks_tsv",
        "ALTER TABLE doc_chunks DROP COLUMN IF EXISTS tsv",
        "DROP INDEX IF EXISTS ix_crosswalk_embedding_hnsw",
        "DROP INDEX IF EXISTS ix_doc_chunks_embedding_hnsw",
        "DROP INDEX IF EXISTS ix_qp_descriptions_embedding_hnsw",
    ):
        op.execute(stmt)

    # ### commands auto generated by Alembic - please adjust! ###'''


def patch(path: pathlib.Path) -> bool:
    src = path.read_text(encoding="utf-8")
    if "ix_doc_chunks_embedding_hnsw" in src:
        print(f"{path.name}: already patched")
        return False

    if "import pgvector.sqlalchemy" not in src:
        src = src.replace(
            "import sqlalchemy as sa\nfrom alembic import op",
            "import pgvector.sqlalchemy\nimport sqlalchemy as sa\nfrom alembic import op",
            1,
        )

    src = src.replace(
        "def upgrade() -> None:\n    # ### commands auto generated by Alembic - please adjust! ###",
        EXTENSIONS_BLOCK,
        1,
    )

    tail = "    # ### end Alembic commands ###\n\n\ndef downgrade() -> None:"
    if tail not in src:
        raise SystemExit(f"{path.name}: could not find the upgrade/downgrade boundary")
    src = src.replace(tail, INDEX_BLOCK, 1)

    src = src.replace(
        "def downgrade() -> None:\n    # ### commands auto generated by Alembic - please adjust! ###",
        DOWNGRADE_BLOCK,
        1,
    )

    path.write_text(src, encoding="utf-8")
    print(f"{path.name}: patched")
    return True


def main() -> int:
    targets = sorted(VERSIONS.glob("*_initial_schema_*.py"))
    if not targets:
        print("no initial-schema migration found", file=sys.stderr)
        return 1
    for target in targets:
        patch(target)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
