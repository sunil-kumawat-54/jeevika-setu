"""Generate ``docs/ingest-report.md`` from the provenance blocks in ``seeds/``.

The no-fabrication policy requires that, for every external source deviation, the
report states: expected behaviour, actual behaviour, cause, fallback, impact and
how to switch back to the real source. This module derives all of that from the
committed seed files, so the report can never drift from what was actually
fetched.
"""

from __future__ import annotations

import datetime as dt
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from pipelines.common import (  # noqa: E402
    REPO,
    SEEDS,
    PipelineResult,
    read_seed,
    seed_fingerprint,
)

SEED_ORDER = (
    ("districts.json", "00", "Districts — Local Government Directory"),
    ("kaushalverse_qualifications.json", "02", "NCVET Kaushalverse qualification register"),
    ("pmajay_courses.json", "01", "PM-AJAY GIA course catalogue"),
    ("crosswalk.json", "04", "Curated aspiration -> QP crosswalk"),
    ("qp_descriptions.json", "04", "QP description embeddings"),
    ("centre_supply.json", "05", "District training-centre supply"),
    ("training_centres.json", "05", "Canonical training centres"),
    ("programmes.json", "05", "Canonical training programmes"),
    ("opportunities.json", "05", "Canonical jobs and self-employment opportunities"),
    ("district_demand.json", "05", "Canonical district/block demand"),
    ("doc_chunks.json", "06", "Guidelines corpus for hybrid RAG"),
)

HEADER = """# docs/ingest-report.md — AVSAR ingestion provenance

**Generated by `pipelines/write_ingest_report.py` from the provenance blocks
inside `seeds/*.json`.** Do not hand-edit: re-run `make ingest` instead.

Every row below states what AVSAR expected from a source, what the source
actually did, and — where they differ — exactly what was substituted. The
governing rule is that synthetic data is acceptable to make the demo work and is
**never** presented as real government data.

| Marker | Meaning |
|---|---|
| `mode: live` | Rows were fetched from the real source named in `source_url`. |
| `mode: synthetic` | The source was unavailable or does not exist; rows are generated and every record carries `synthetic: true`. |
| `synthetic: true` (per row) | Flag is preserved through ingestion -> database -> API -> dashboard badge. |
"""


def _fmt_int(value) -> str:
    try:
        return f"{int(value):,}"
    except (TypeError, ValueError):
        return str(value)


def _summary_table() -> str:
    lines = [
        "| # | Seed file | Mode | Rows | Source | SHA-256 (records) |",
        "|---|---|---|---|---|---|",
    ]
    for filename, number, _label in SEED_ORDER:
        path = SEEDS / filename
        if not path.exists():
            lines.append(f"| {number} | `seeds/{filename}` | _not generated_ | — | — | — |")
            continue
        prov, records = read_seed(path)
        mode = prov.get("mode", "?")
        badge = "**SYNTHETIC**" if prov.get("synthetic") else mode
        source = prov.get("source_url", "—")
        if len(source) > 60:
            source = source[:57] + "…"
        lines.append(
            f"| {number} | `seeds/{filename}` | {badge} | {_fmt_int(len(records))} | "
            f"`{source}` | `{seed_fingerprint(path)[:16]}` |"
        )
    return "\n".join(lines)


def _deviation_sections() -> str:
    blocks: list[str] = []
    for filename, number, label in SEED_ORDER:
        path = SEEDS / filename
        if not path.exists():
            continue
        prov, records = read_seed(path)
        blocks.append(f"### Pipeline {number} — {label}\n")
        blocks.append(f"- **Seed file:** `seeds/{filename}` ({_fmt_int(len(records))} records)")
        blocks.append(f"- **Source URL:** `{prov.get('source_url', '—')}`")
        blocks.append(f"- **Mode:** `{prov.get('mode', '?')}`")
        source_name = prov.get("source_name") or prov.get("pipeline") or filename.removesuffix(".json")
        source_version = prov.get("source_version") or seed_fingerprint(path)[:16]
        blocks.append(f"- **Source name/version:** `{source_name}` / `{source_version}`")
        blocks.append(f"- **Fetched at:** `{prov.get('fetched_at', '—')}`")
        blocks.append(f"- **Freshness at:** `{prov.get('freshness_at', '—')}`")
        blocks.append(f"- **Verification:** `{prov.get('verification_status', 'unverified')}`")
        blocks.append(f"- **Record fingerprint:** `{seed_fingerprint(path)}`")
        if prov.get("http_status") is not None:
            blocks.append(f"- **Last HTTP status:** `{prov['http_status']}`")

        if prov.get("synthetic"):
            blocks.append("")
            blocks.append("**Deviation**")
            blocks.append("")
            blocks.append(
                f"- **Expected:** rows fetched from `{prov.get('source_url', 'the source')}`."
            )
            blocks.append(
                f"- **Actual:** {prov.get('failure_reason') or 'no live source exists for this table.'}"
            )
            blocks.append(f"- **Fallback:** {prov.get('fallback_note') or 'synthetic snapshot generated.'}")
            blocks.append(
                "- **Impact:** every record carries `synthetic: true`; the flag survives into "
                "the database column and is rendered as a badge in the officer dashboard and "
                "in the demo footer."
            )
            blocks.append(
                "- **How to switch to the real source:** restore access to the URL above and "
                f"re-run `make ingest` (or `python pipelines/{number}_*.py`). The pipeline "
                "prefers live data whenever the fetch succeeds; no code change is needed."
            )
        if prov.get("notes"):
            blocks.append("")
            blocks.append("**Observations**")
            blocks.append("")
            for note in prov["notes"]:
                blocks.append(f"- {note}")
        blocks.append("")
    return "\n".join(blocks)


def _join_section() -> str:
    path = SEEDS / "join_report.json"
    if not path.exists():
        return "_Join report not generated yet — run `python pipelines/03_join_qp_level.py`._\n"
    _, records = read_seed(path)
    if not records:
        return "_Join report empty._\n"
    report = records[0]
    lines = [
        "| Metric | Value |",
        "|---|---|",
        f"| Courses | {_fmt_int(report.get('total_courses'))} |",
        f"| Qualifications | {_fmt_int(report.get('total_qualifications'))} |",
        f"| Matched | {_fmt_int(report.get('matched'))} ({report.get('match_rate_pct')}%) |",
        f"| Unmatched | {_fmt_int(report.get('unmatched'))} |",
        f"| Register-assigned NSQF level | {_fmt_int(report.get('register_assigned_level'))} |",
        f"| Hours-inferred level (flagged) | {_fmt_int(report.get('hours_inferred_level'))} |",
        f"| Half-level rows | {_fmt_int(report.get('half_level_rows'))} ({report.get('half_level_pct')}%) |",
        f"| Fuzzy threshold | {report.get('fuzzy_threshold')} |",
        "",
        "Match strategies: "
        + ", ".join(f"`{k}`={_fmt_int(v)}" for k, v in sorted((report.get("strategies") or {}).items())),
        "",
    ]
    if report.get("match_rate_is_tautological"):
        lines.append(
            "> **Caveat — the match rate above is tautological.** Pipeline 01 fell back, and "
            "its fallback derives course rows *from this same NCVET register*, so of course "
            "they join. This number is **not** evidence that the real PM-AJAY catalogue joins "
            "cleanly to Kaushalverse. PLAN.md §5.1 expects imperfect coverage against the live "
            "portal, and the hours-derived level fallback remains implemented and unit-tested "
            "for that case."
        )
        lines.append("")
    return "\n".join(lines)


def _half_level_section() -> str:
    path = SEEDS / "kaushalverse_qualifications.json"
    if not path.exists():
        return ""
    _, records = read_seed(path)
    levelled = [r for r in records if r.get("nsqf_level") is not None]
    if not levelled:
        return ""
    half = [r for r in levelled if float(r["nsqf_level"]) % 1 != 0]
    from collections import Counter

    dist = Counter(str(r["nsqf_level"]) for r in levelled)
    lines = [
        f"Of {_fmt_int(len(levelled))} levelled qualifications, **{_fmt_int(len(half))} "
        f"({100 * len(half) / len(levelled):.1f}%) sit at a half NSQF level**.",
        "",
        "research.md §3.2 predicted ~24% from a 136-record sample; this is the whole corpus, "
        "and it confirms the prediction. RULE 5 exists because of exactly this: any integer-only "
        "filter would silently mishandle roughly a quarter of the catalogue.",
        "",
        "| NSQF level | Qualifications |",
        "|---|---|",
    ]
    for level, count in sorted(dist.items(), key=lambda kv: float(kv[0])):
        marker = " ← half level" if float(level) % 1 != 0 else ""
        lines.append(f"| {level} | {_fmt_int(count)}{marker} |")
    lines.append("")
    return "\n".join(lines)


def _nco_section() -> str:
    path = SEEDS / "kaushalverse_qualifications.json"
    if not path.exists():
        return ""
    _, records = read_seed(path)
    if not records:
        return ""
    populated = sum(1 for r in records if r.get("nco_code"))
    return (
        f"`ncoCode` is populated in **{populated} of {_fmt_int(len(records))}** records "
        "fetched from Kaushalverse.\n\n"
        "research.md §3.3 called this the hardest data problem in the brief: the chain the "
        "problem statement implies is *spoken aspiration -> occupation concept -> NCO-2015 code "
        "-> NSQF-aligned QP*, and **no register publishes the NCO link**. This ingest run "
        "confirms it against the full corpus rather than a sample. That void is what "
        "`data/crosswalk/*.yaml` fills, and why the crosswalk is the project's contribution "
        "rather than an implementation detail.\n"
    )


def write_report(
    results: list[PipelineResult] | None = None,
    failures: list[str] | None = None,
    path: pathlib.Path | None = None,
) -> pathlib.Path:
    path = path or REPO / "docs" / "ingest-report.md"
    path.parent.mkdir(parents=True, exist_ok=True)

    parts = [
        HEADER,
        f"\n_Last generated: {dt.datetime.now(dt.UTC).strftime('%Y-%m-%d %H:%M UTC')}_\n",
        "\n## 1. Seed inventory\n",
        _summary_table(),
        "\n\n## 2. Per-pipeline provenance and deviations\n",
        _deviation_sections(),
        "\n## 3. QP <-> NSQF join coverage\n",
        _join_section(),
        "\n## 4. Half-level NSQF distribution (RULE 5 evidence)\n",
        _half_level_section(),
        "\n## 5. The NCO-2015 gap (why the crosswalk exists)\n",
        _nco_section(),
        "\n## 6. Runtime guarantee\n",
        "\nThe running service never contacts `pmajay.dosje.gov.in` or "
        "`kaushalverse.ncvet.gov.in`. Those hosts appear only in `pipelines/`, which is "
        "executed by `make ingest` and never imported by `services/core`. "
        "`services/core/tests/test_gate2_ingestion.py` asserts this by scanning the runtime "
        "package for those hostnames.\n",
        "\n## 7. Loader contract\n\n"
        "`pipelines/load_to_db.py` reports input, inserted, updated, skipped, and failed "
        "counts for canonical source snapshots. Natural-key upserts preserve surrogate IDs; "
        "unchanged rows are skipped by stable record fingerprint. Missing optional snapshots "
        "are reported as unavailable rather than treated as live data. Synthetic centre supply "
        "creates no coordinates and remains marked `coordinate_status=synthetic`.\n",
    ]

    if failures:
        parts.append("\n## 8. Failures in the last run\n\n")
        for failure in failures:
            parts.append(f"- `{failure}`\n")

    path.write_text("".join(parts), encoding="utf-8")
    return path


if __name__ == "__main__":
    print(write_report())
